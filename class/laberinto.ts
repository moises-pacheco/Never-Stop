    construirNivel(nivel: string[][]) {

        //Adapta las dimensiones del nivel a la pantalla.
        this.ajustarTamanioNivel(nivel);

        nivel.forEach((fila, indiceFila) => {
            fila.forEach((celda: any, indiceColumna) => {
                if (celda === "#") {
                    //Adaptar el labrinto
                    let pared = document.createElement("div");
                    pared.classList.add("pared");
                    //Colocar a cada uno en su posición:
                    pared.style.left = indiceColumna * this.tamanoCelda + "px";
                    pared.style.top = indiceFila * this.tamanoCelda + "px"
                    pared.style.width = this.tamanoCelda + "px";
                    pared.style.height = this.tamanoCelda + "px";
                    this.divsLaberinto.push(pared); // Se agregan los divs al array para calcular después los elementos
                    this.calcularRangoParedes(this.divsLaberinto);
                    this.laberinto.appendChild(pared);

                }
            })
        })
    }


